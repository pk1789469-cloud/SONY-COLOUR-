export const getLanguage = (): Language => {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = localStorage.getItem('tg_gaming_lang');
    return saved === 'hi' ? 'hi' : 'en';
  } catch {
    return 'en';
  }
};

export const setLanguage = (lang: Language) => {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem('tg_gaming_lang', lang);
    window.dispatchEvent(new CustomEvent('tg_language_changed', { detail: lang }));
  } catch {
    // ignore
  }
};
